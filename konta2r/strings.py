def t(key: str, lang: str = DEFAULT_LANG, **params) -> str:
    """Texto en el idioma pedido (fallback español, luego la clave)."""
    entry = STRINGS.get(key)
    if not entry:
        return key
    txt = entry.get(lang) or entry.get(DEFAULT_LANG) or key
    if params:
        try:
            txt = txt.format(**params)
        except (KeyError, IndexError, ValueError):
            pass
    return txt


def class_name(key: str, lang: str = DEFAULT_LANG) -> str:
    """Nombre visible de una clase contable en el idioma pedido."""
    entry = CLASS_NAMES.get(key, {})
    return entry.get(lang) or entry.get(DEFAULT_LANG) or key
